#![cfg_attr(windows, windows_subsystem = "windows")]

#[cfg(not(windows))]
fn main() -> anyhow::Result<()> {
    anyhow::bail!("narrowd-session-launcher is only supported on Windows")
}

#[cfg(windows)]
mod imp {
    use std::fs;
    use std::path::PathBuf;

    use anyhow::{Context, Result};
    use narrowd::config::AppConfig;
    use narrowd::logging;
    use narrowd::sshd;

    const DEFAULT_PORT: u16 = 2223;
    const DEFAULT_LISTEN_ADDRESS: &str = "0.0.0.0";

    #[derive(Clone, Debug)]
    struct SessionPaths {
        narrowd_root: PathBuf,
        config_path: PathBuf,
        host_key_path: PathBuf,
        log_dir: PathBuf,
        log_file: PathBuf,
        authorized_keys_path: PathBuf,
        shell_path: String,
    }

    pub fn main() -> Result<()> {
        let paths = resolve_paths()?;
        let log_path = paths.log_file.clone();

        match run(paths) {
            Ok(()) => Ok(()),
            Err(err) => {
                logging::append_bootstrap_error(
                    Some(log_path.as_path()),
                    &format!("session launcher failed: {err:#}"),
                );
                Err(err)
            }
        }
    }

    fn run(paths: SessionPaths) -> Result<()> {
        fs::create_dir_all(&paths.narrowd_root)
            .with_context(|| format!("failed to create {}", paths.narrowd_root.display()))?;
        fs::create_dir_all(&paths.log_dir)
            .with_context(|| format!("failed to create {}", paths.log_dir.display()))?;

        ensure_default_config(&paths)?;

        let config = AppConfig::load(Some(paths.config_path.clone())).with_context(|| {
            format!(
                "failed to load session config {}",
                paths.config_path.display()
            )
        })?;
        logging::init(config.log_level, Some(paths.log_file.clone()))?;

        let runtime = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .context("failed to create Tokio runtime for the session launcher")?;
        runtime.block_on(sshd::run(config))
    }

    fn resolve_paths() -> Result<SessionPaths> {
        let home_dir = dirs::home_dir().context("unable to determine the user home directory")?;
        let local_app_data = dirs::data_local_dir()
            .or_else(|| std::env::var_os("LOCALAPPDATA").map(PathBuf::from))
            .context("unable to determine the Local AppData directory")?;
        let narrowd_root = local_app_data.join("narrowd");
        let config_path = narrowd_root.join("narrowd.conf");
        let host_key_path = narrowd_root.join("ssh_host_ed25519_key");
        let log_dir = narrowd_root.join("log");
        let log_file = log_dir.join("narrowd.log");
        let authorized_keys_path = home_dir.join(".ssh").join("authorized_keys");

        Ok(SessionPaths {
            narrowd_root,
            config_path,
            host_key_path,
            log_dir,
            log_file,
            authorized_keys_path,
            shell_path: default_shell_path(),
        })
    }

    fn default_shell_path() -> String {
        let default = PathBuf::from(r"C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe");
        if default.is_file() {
            return default.display().to_string();
        }

        "powershell.exe".to_string()
    }

    fn ensure_default_config(paths: &SessionPaths) -> Result<()> {
        if paths.config_path.exists() {
            return Ok(());
        }

        let config = render_default_config(paths);
        fs::write(&paths.config_path, config)
            .with_context(|| format!("failed to write {}", paths.config_path.display()))
    }

    fn render_default_config(paths: &SessionPaths) -> String {
        format!(
            "\
# Generated by the narrowd MSIX session launcher.
# Edit this file to customize the session-scoped SSH daemon.
Port {port}
ListenAddress {listen_address}

HostKey {host_key}
AuthorizedKeysFile {authorized_keys}

Shell {shell}
ExecMode powershell
PermitTTY yes
PermitExec yes

Subsystem sftp internal-sftp
AllowTcpForwarding yes
AllowRemoteForwarding yes
GatewayPorts yes

# Public exposure hardening defaults
MaxUnauthConnectionsGlobal 16
MaxUnauthConnectionsPerIp 3
MaxUnauthConnectionsPerSubnet 8
NewConnectionsPerMinutePerIp 12
NewConnectionsBurstPerIp 4
LoginGraceTime 15s
ClientBannerTimeout 5s
KexStartTimeout 5s
MaxAuthAttempts 4
AuthRejectionTime 2s
AuthFailureBanThreshold 8
AuthFailureBanWindow 10m
AuthFailureBanDuration 15m
InactivityTimeout 15m
KeepaliveInterval 30s
KeepaliveMax 3
ChannelBufferSize 32
EventBufferSize 16
WindowSize 1048576
MaximumPacketSize 32768
NoDelay yes
AuthorizedKeysMaxSize 256KiB
AuthorizedKeysMaxEntries 128
AuthorizedKeysReloadInterval 2s

LogLevel info
",
            port = DEFAULT_PORT,
            listen_address = DEFAULT_LISTEN_ADDRESS,
            host_key = paths.host_key_path.display(),
            authorized_keys = paths.authorized_keys_path.display(),
            shell = paths.shell_path,
        )
    }
}

#[cfg(windows)]
fn main() -> anyhow::Result<()> {
    imp::main()
}
